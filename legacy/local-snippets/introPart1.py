# Integer (int)
x = 5
# Floating point (float)
x = 5.12
# String (str)
x = "Hello"
# List
x = [5, 5.12, "Hello"]
# Boolean (bool)
x = True
x = False
# Dictionary (dict)
x = {"key1":"value1",
     "key2":2,
     "key3":3.00}

# Changing Types
x = "5.432" # this is a string by default because it has ""
x = float(x) # this changes x from a string to a float number
x = str(x) # this changes x back into the originial string
x = int(float(x)) # this changes x into the integer 5...notice that
                  # when converting from a string to an integer,
                  # you need to convert to a float first if there
                  # are decimals



                  


